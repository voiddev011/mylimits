import { createApp } from './app';
import { transitFromConfig } from './transit-kms';
import { hostedDrivers } from './hosted';
import { configFromEnv } from './config';
import { poolFor,migrate } from './db';
const config=configFromEnv(),pool=poolFor(config.databaseUrl);
const kms=await transitFromConfig(config.transit);
if(hostedDrivers.size&&(!kms||!config.oidc))throw new Error('Hosted providers require configured identity and protected credential storage.');
await migrate(pool);const app=createApp({config,pool,kms});
app.addHook('onClose',async()=>pool.end());
await app.listen({host:config.host,port:config.port});
console.log(`MyLimits snapshot-only API listening on ${config.host}:${config.port}; OIDC ${config.oidc?'configured':'not configured (authentication fails closed)'}.`);
for(const signal of ['SIGTERM','SIGINT'] as const)process.once(signal,()=>void app.close());
